    private val WHITESPACE = Regex("[\\s\\u3000]")
    private val PUNCT = Regex("[\\u00b7\\u30fb\\u2027\\uff0e.,\\u3001_\\u2013\\u2014\\uff0d~~()\\uff08\\uff09\\[\\]\\u3010\\u3011:\\uff1a/\\\\|!!\\uff1f?\"'\\u2018\\u2019\\u201c\\u201d*+&@#$%%\\uff1b;=\\uff1d<>\\u300a\\u300b\\u00ab\\u00bb]")

    fun normKey(s: String): String {
        val nfkc = Normalizer.normalize(s, Normalizer.Form.NFKC).lowercase()
        val mapped = buildString(nfkc.length) {
            for (ch in nfkc) append(T2S[ch] ?: ch)
        }
        return PUNCT.replace(WHITESPACE.replace(mapped, ""), "")
    }

    /** 归一键 -> (原文标签 -> 出现次数)。仅保留含 >=2 个不同原文形态的组。 */
    fun variantGroups(tagCounts: Map<String, Int>): List<VariantGroup> {
        val byKey = LinkedHashMap<String, MutableMap<String, Int>>()
        for ((tag, cnt) in tagCounts) {
            byKey.getOrPut(normKey(tag)) { LinkedHashMap() }[tag] = cnt
        }
        return byKey.asSequence()
            .filter { it.value.size > 1 }
            .map { (key, variants) -> VariantGroup(key, variants.toMap()) }
            .sortedByDescending { it.variants.size }
            .toList()
    }
